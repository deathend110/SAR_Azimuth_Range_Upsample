function V5_ValidateResults()
% 验收V5结果文件、行数、有限值和V4数值回归。

cfg=V5Core.config(); main_dir=fullfile(cfg.output_root,"MainEvaluation");
threshold_dir=fullfile(cfg.output_root,"ThresholdSensitivity");
mechanism_dir=fullfile(cfg.output_root,"Mechanism");
noise_dir=fullfile(cfg.output_root,"NoiseEvaluation");
required=[ ...
    fullfile(main_dir,"V5_Main_Summary.csv"), ...
    fullfile(main_dir,"V5_Main_Detail.csv"), ...
    fullfile(main_dir,"V5_TableIII_Metrics.csv"), ...
    fullfile(main_dir,"V5_RT_PairedTests.csv"), ...
    fullfile(main_dir,"V5_ENL_ROI_Manifest.csv"), ...
    fullfile(threshold_dir,"V5_RT_As_Summary.csv"), ...
    fullfile(threshold_dir,"V5_RT_As_Detail.csv"), ...
    fullfile(threshold_dir,"V5_RT_SSIM_AsCurve.png"), ...
    fullfile(mechanism_dir,"V5_Mechanism_Metrics.csv"), ...
    fullfile(mechanism_dir,"V5_Scene_Metrics.csv"), ...
    fullfile(mechanism_dir,"V5_Mechanism_Common4x4.png"), ...
    fullfile(mechanism_dir,"V5_Scene_SharedColorbar.png"), ...
    fullfile(noise_dir,"V5_Noise_RawDetail.csv"), ...
    fullfile(noise_dir,"V5_Noise_SampleMeans.csv"), ...
    fullfile(noise_dir,"V5_Noise_Summary.csv"), ...
    fullfile(noise_dir,"V5_Noise_PairedTests.csv"), ...
    fullfile(noise_dir,"V5_Noise_ActualSNR.csv"), ...
    fullfile(noise_dir,"V5_Noise_CleanBaseline.csv"), ...
    fullfile(noise_dir,"V5_Noise_ENL_ROI_Manifest.csv"), ...
    fullfile(noise_dir,"V5_Noise_CleanGT_Curves.png"), ...
    fullfile(noise_dir,"V5_Noise_CleanGT_Curves.pdf"), ...
    fullfile(noise_dir,"V5_Noise_NoisyGT_Curves.png"), ...
    fullfile(noise_dir,"V5_Noise_NoisyGT_Curves.pdf"), ...
    fullfile(noise_dir,"V5_Noise_NoisyGT_AutoScale_Curves.png"), ...
    fullfile(noise_dir,"V5_Noise_NoisyGT_AutoScale_Curves.pdf"), ...
    fullfile(noise_dir,"V5_Noise_NoisyGT_FocusCurves.png"), ...
    fullfile(noise_dir,"V5_Noise_NoisyGT_FocusCurves.pdf")];
assert(all(isfile(required)),"V5验收所需文件不完整。");

main=readtable(fullfile(main_dir,"V5_Main_Summary.csv"),"TextType","string");
detail=readtable(fullfile(main_dir,"V5_Main_Detail.csv"),"TextType","string");
table_metrics=readtable(fullfile(main_dir,"V5_TableIII_Metrics.csv"),"TextType","string");
paired=readtable(fullfile(main_dir,"V5_RT_PairedTests.csv"),"TextType","string");
main_roi=readtable(fullfile(main_dir,"V5_ENL_ROI_Manifest.csv"),"TextType","string");
assert(height(main)==19 && height(detail)==19*70,"V5主结果行数不正确。");
assert(height(table_metrics)==20,"V5论文主表应包含GT和19个分配组。");
assert(height(paired)==numel(cfg.Q_list) && isequal(paired.Q.',cfg.Q_list), ...
    "V5 RT配对检验预算不完整。");
assert(all(main.SampleCount==70) && all(main.ENLSampleCount==20), ...
    "V5主结果样本数不正确。");
assert(all(isfinite(main.PSNR_Mean)) && all(isfinite(main.SSIM_Mean)) && ...
    all(isfinite(main.Entropy_Mean)) && all(isfinite(main.ENL_Mean)), ...
    "V5主结果存在非有限指标。");

threshold=readtable(fullfile(threshold_dir,"V5_RT_As_Summary.csv"),"TextType","string");
threshold_detail=readtable(fullfile(threshold_dir,"V5_RT_As_Detail.csv"),"TextType","string");
assert(height(threshold)==3*numel(cfg.As_list),"RT敏感性汇总行数不正确。");
assert(height(threshold_detail)==3*numel(cfg.As_list)*70,"RT敏感性明细行数不正确。");
assert(all(isfinite(threshold.PSNR_Mean)) && all(isfinite(threshold.SSIM_Mean)), ...
    "RT敏感性指标存在非有限值。");

mechanism=readtable(fullfile(mechanism_dir,"V5_Mechanism_Metrics.csv"),"TextType","string");
scenes=readtable(fullfile(mechanism_dir,"V5_Scene_Metrics.csv"),"TextType","string");
assert(height(mechanism)==4 && height(scenes)==4,"V5机制结果行数不正确。");

raw=readtable(fullfile(noise_dir,"V5_Noise_RawDetail.csv"),"TextType","string");
sample_means=readtable(fullfile(noise_dir,"V5_Noise_SampleMeans.csv"),"TextType","string");
noise_summary=readtable(fullfile(noise_dir,"V5_Noise_Summary.csv"),"TextType","string");
noise_tests=readtable(fullfile(noise_dir,"V5_Noise_PairedTests.csv"),"TextType","string");
snr_audit=readtable(fullfile(noise_dir,"V5_Noise_ActualSNR.csv"),"TextType","string");
baseline=readtable(fullfile(noise_dir,"V5_Noise_CleanBaseline.csv"),"TextType","string");
noise_roi=readtable(fullfile(noise_dir,"V5_Noise_ENL_ROI_Manifest.csv"), ...
    "TextType","string");
n_snr=numel(cfg.SNR_dB_list);
assert(height(raw)==3*n_snr*70*cfg.noise_repeats,"噪声重复级明细行数不正确。");
assert(height(sample_means)==3*n_snr*70,"噪声样本均值行数不正确。");
assert(height(noise_summary)==3*n_snr,"噪声汇总行数不正确。");
assert(height(noise_tests)==2*2*n_snr,"噪声配对检验行数不正确。");
assert(height(snr_audit)==n_snr*70*cfg.noise_repeats,"实际SNR审计行数不正确。");
assert(height(baseline)==3,"clean baseline应包含三个分配。");
assert(height(noise_roi)==20,"噪声实验ENL ROI清单应包含20个样本。");
roi_names=["SampleID","ROITop","ROILeft","ROIHeight","ROIWidth"];
assert(isequaln(main_roi(:,roi_names),noise_roi(:,roi_names)), ...
    "噪声实验与主实验的ENL ROI清单不一致。");
metric_names=["PSNR_CleanGT_Mean","SSIM_CleanGT_Mean", ...
    "PSNR_NoisyGT_Mean","SSIM_NoisyGT_Mean"];
for name=metric_names
    assert(all(isfinite(noise_summary.(name))),"噪声汇总%s存在非有限值。",name);
end
assert(all(noise_summary.ENLSampleCount==20) && ...
    all(isfinite(noise_summary.ENL_Mean)) && all(isfinite(noise_summary.ENL_Std)), ...
    "噪声汇总ENL样本数或指标不正确。");
assert(all(baseline.ENLSampleCount==20) && all(isfinite(baseline.ENL_Mean)) && ...
    all(isfinite(baseline.ENL_Std)),"clean baseline ENL不完整。");
raw_is_enl=ismember(raw.Dataset,cfg.enl_dataset_names);
sample_is_enl=ismember(sample_means.Dataset,cfg.enl_dataset_names);
assert(all(isfinite(raw.ENL(raw_is_enl))) && all(isnan(raw.ENL(~raw_is_enl))), ...
    "噪声重复级ENL未严格限定在20个ENL样本上。");
assert(all(isfinite(sample_means.ENL(sample_is_enl))) && ...
    all(isnan(sample_means.ENL(~sample_is_enl))), ...
    "噪声样本级ENL未严格限定在20个ENL样本上。");

% 验证重复级ENL先在样本内平均，再在20个样本间汇总。
raw_enl=raw(raw_is_enl,:);
grouped=groupsummary(raw_enl,["SNR_dB","GroupName","SampleID"],"mean","ENL");
sample_enl=sample_means(sample_is_enl, ...
    ["SNR_dB","GroupName","SampleID","ENL"]);
grouped=sortrows(grouped,["SNR_dB","GroupName","SampleID"]);
sample_enl=sortrows(sample_enl,["SNR_dB","GroupName","SampleID"]);
assert(height(grouped)==height(sample_enl) && ...
    max(abs(grouped.mean_ENL-sample_enl.ENL))<1e-12, ...
    "噪声ENL的重复级到样本级聚合不一致。");
for row_idx=1:height(noise_summary)
    mask=sample_enl.SNR_dB==noise_summary.SNR_dB(row_idx) & ...
        sample_enl.GroupName==noise_summary.GroupName(row_idx);
    values=sample_enl.ENL(mask);
    assert(numel(values)==20 && ...
        abs(mean(values)-noise_summary.ENL_Mean(row_idx))<1e-12 && ...
        abs(std(values)-noise_summary.ENL_Std(row_idx))<1e-12, ...
        "噪声ENL的样本级到汇总级聚合不一致。");
end
assert(max(abs(snr_audit.TargetSNR_dB-snr_audit.ActualSNR_dB))<0.1, ...
    "有限样本实际SNR偏离目标超过0.1 dB。");

regressAgainstV4(cfg,main,mechanism);
fprintf("V5结果验收通过：主结果19组，噪声%d个SNR点、%d次重复。\n", ...
    n_snr,cfg.noise_repeats);
end

function regressAgainstV4(cfg,v5_main,v5_mechanism)
v4_main_path=fullfile(cfg.repo_root,"V4_Experiments_Output", ...
    "MainEvaluation","V4_Main_Summary.csv");
if isfile(v4_main_path)
    v4=readtable(v4_main_path,"TextType","string");
    [ok,idx]=ismember(v5_main.GroupName,v4.GroupName); assert(all(ok),"V4缺少V5主实验组。");
    assert(max(abs(v5_main.PSNR_Mean-v4.PSNR_Mean(idx)))<1e-5, ...
        "V5与V4主结果PSNR回归不一致。");
    assert(max(abs(v5_main.SSIM_Mean-v4.SSIM_Mean(idx)))<1e-6, ...
        "V5与V4主结果SSIM回归不一致。");
end
v4_mech_path=fullfile(cfg.repo_root,"V4_Experiments_Output", ...
    "Mechanism","V4_Mechanism_Metrics.csv");
if isfile(v4_mech_path)
    v4=readtable(v4_mech_path,"TextType","string");
    [ok,idx]=ismember(v5_mechanism.Allocation,v4.Allocation); assert(all(ok),"V4缺少V5机制组。");
    names=["OffSupport","RangeLeakage","AzimuthLeakage"];
    for name=names
        assert(max(abs(v5_mechanism.(name)-v4.(name)(idx)))<1e-10, ...
            "V5与V4机制指标%s回归不一致。",name);
    end
end
end
