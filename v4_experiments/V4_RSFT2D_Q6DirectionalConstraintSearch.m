function V4_RSFT2D_Q6DirectionalConstraintSearch()
% q=6单向分配的方向一致二维RSFT约束搜索。
%
% R6A1固定fa/Ba=0，仅搜索STR和fr/Br；
% R1A6固定fr/Br=0，仅搜索STR和fa/Ba。

cfg = V4Core.config();
addpath(cfg.repo_root, cfg.experiment_dir);

source_file = fullfile(cfg.output_root, ...
    "RSFT2DAllocationSearch", "RSFT2D_AllData.mat");
assert(isfile(source_file), "未找到二维RSFT搜索结果：%s", source_file);

loaded = load(source_file, ...
    "group_defs", "group_results", "sample_manifest", ...
    "calibration_indices", "test_indices", "signature");
validateSourceResult(loaded);

experiment_cfg = buildExperimentConfig();
target_defs = buildTargetDefinitions(loaded);
validateUnconstrainedBaselines(target_defs, loaded.group_results);

output_dir = fullfile(cfg.output_root, ...
    "RSFT2D_Q6DirectionalConstraintSearch");
checkpoint_dir = fullfile(output_dir, "Checkpoints");
V4Core.ensureDir(output_dir);
V4Core.ensureDir(checkpoint_dir);

S60 = load(cfg.parameter_file);
[sample_cache, manifest_now] = V4Core.buildSampleCache(cfg, S60);
assert(isequaln(manifest_now, loaded.sample_manifest), ...
    "当前样本清单与二维RSFT搜索结果不一致。");

calibration_indices = loaded.calibration_indices(:);
test_indices = loaded.test_indices(:);
validateSampleSplit(loaded.sample_manifest, ...
    calibration_indices, test_indices);

azimuth_bandwidth_Hz = loaded.signature.azimuth_bandwidth_Hz;
assert(isscalar(azimuth_bandwidth_Hz) && ...
    isfinite(azimuth_bandwidth_Hz) && azimuth_bandwidth_Hz > 0, ...
    "二维RSFT搜索结果中的方位带宽无效。");

signature = struct( ...
    "experiment", "V4_RSFT2D_Q6DirectionalConstraintSearch", ...
    "seed", cfg.seed, ...
    "source_signature", loaded.signature, ...
    "coarse_STR_dB", experiment_cfg.coarse_STR_dB, ...
    "coarse_active_frequency", ...
    experiment_cfg.coarse_active_frequency, ...
    "fine_STR_offsets", experiment_cfg.fine_STR_offsets, ...
    "fine_frequency_offsets", experiment_cfg.fine_frequency_offsets, ...
    "max_refinement_rounds", ...
    experiment_cfg.max_refinement_rounds, ...
    "calibration_sample_ids", ...
    loaded.sample_manifest.SampleID(calibration_indices).', ...
    "test_sample_ids", ...
    loaded.sample_manifest.SampleID(test_indices).');

requested_workers = min( ...
    experiment_cfg.max_parallel_workers, max(1, feature("numcores")));
pool = gcp("nocreate");
if isempty(pool)
    try
        pool = parpool("threads", requested_workers);
        num_workers = pool.NumWorkers;
    catch pool_error
        warning("V4:ParallelPoolUnavailable", ...
            "并行池启动失败，将串行执行参数搜索：%s", pool_error.message);
        num_workers = 0;
    end
else
    num_workers = min(pool.NumWorkers, requested_workers);
end

fprintf("\n=== q=6单向分配方向约束搜索 ===\n");
fprintf("校准样本：%d；测试样本：%d；参数搜索线程：%d\n", ...
    numel(calibration_indices), numel(test_indices), ...
    max(1, num_workers));

num_targets = numel(target_defs);
target_results = cell(num_targets, 1);

for target_idx = 1:num_targets
    target = target_defs(target_idx);
    group = loaded.group_defs(target.SourceGroupIdx);
    group_signature = struct( ...
        "global_signature", signature, ...
        "GroupName", target.GroupName, ...
        "ActiveDirection", target.ActiveDirection, ...
        "FixedFrOverBr", target.FixedFrOverBr, ...
        "FixedFaOverBa", target.FixedFaOverBa);

    fprintf("\n[%d/%d] %s：%s\n", ...
        target_idx, num_targets, target.GroupName, target.ModelName);

    stage_results = cell( ...
        experiment_cfg.max_refinement_rounds + 1, 1);
    stage_results{1} = runGridStage( ...
        group, target, "coarse", ...
        experiment_cfg.coarse_STR_dB, ...
        experiment_cfg.coarse_active_frequency, ...
        sample_cache, calibration_indices, S60, ...
        azimuth_bandwidth_Hz, num_workers, ...
        checkpoint_dir, group_signature);

    best = stage_results{1}.best;
    completed_stage_count = 1;

    for refine_round = 1:experiment_cfg.max_refinement_rounds
        [fine_STR, fine_frequency] = buildFineGrid( ...
            best, experiment_cfg);
        stage_name = "fine" + string(refine_round);

        stage_results{refine_round + 1} = runGridStage( ...
            group, target, stage_name, fine_STR, fine_frequency, ...
            sample_cache, calibration_indices, S60, ...
            azimuth_bandwidth_Hz, num_workers, ...
            checkpoint_dir, group_signature);

        best = stage_results{refine_round + 1}.best;
        completed_stage_count = refine_round + 1;
        if ~stage_results{refine_round + 1}.TouchesExpandableBoundary
            break;
        end

        fprintf("  %s最优点触碰可扩展边界，继续局部细化。\n", ...
            stage_name);
    end

    stage_results = stage_results(1:completed_stage_count);
    constrained_test = evaluateLockedParameters( ...
        group, target, best, sample_cache, test_indices, S60, ...
        azimuth_bandwidth_Hz, checkpoint_dir, group_signature);

    unconstrained_result = ...
        loaded.group_results{target.SourceGroupIdx};
    validateBaselineTestOrder( ...
        unconstrained_result.test_result, test_indices);

    target_result = struct();
    target_result.signature = group_signature;
    target_result.target = target;
    target_result.group = group;
    target_result.stage_results = stage_results;
    target_result.best = best;
    target_result.constrained_test = constrained_test;
    target_result.unconstrained_best = unconstrained_result.best;
    target_result.unconstrained_test = unconstrained_result.test_result;
    target_results{target_idx} = target_result;

    fprintf("  约束最优：STR=%+.2f dB，fr/Br=%.3f，fa/Ba=%.3f\n", ...
        best.STRdB, best.FrOverBr, best.FaOverBa);
    fprintf("  Test PSNR=%.6f dB，Test SSIM=%.6f\n", ...
        mean(constrained_test.PSNR), mean(constrained_test.SSIM));
end

[summary_table, detail_table, search_grid_table, paired_tests_table] = ...
    aggregateResults(target_results, loaded.sample_manifest, test_indices);
validateFinalResults( ...
    target_results, summary_table, detail_table, search_grid_table);

representative_images = buildRepresentativeImages( ...
    target_results, sample_cache, loaded.sample_manifest, ...
    test_indices, S60, azimuth_bandwidth_Hz);

summary_path = fullfile(output_dir, ...
    "Q6_DirectionalConstraint_GroupSummary.csv");
detail_path = fullfile(output_dir, ...
    "Q6_DirectionalConstraint_TestDetail.csv");
grid_path = fullfile(output_dir, ...
    "Q6_DirectionalConstraint_SearchGrid.csv");
paired_path = fullfile(output_dir, ...
    "Q6_DirectionalConstraint_PairedTests.csv");

writetable(summary_table, summary_path);
writetable(detail_table, detail_path);
writetable(search_grid_table, grid_path);
writetable(paired_tests_table, paired_path);

for target_idx = 1:num_targets
    figure_path = fullfile(output_dir, ...
        target_defs(target_idx).GroupName + ...
        "_DirectionalConstraint_Representative.png");
    exportRepresentativeFigure( ...
        representative_images{target_idx}, ...
        target_defs(target_idx), figure_path);
end

save(fullfile(output_dir, ...
    "Q6_DirectionalConstraint_AllData.mat"), ...
    "cfg", "experiment_cfg", "signature", "target_defs", ...
    "target_results", "summary_table", "detail_table", ...
    "search_grid_table", "paired_tests_table", ...
    "representative_images", "-v7.3");
writeMetadata(output_dir, signature, target_defs, ...
    summary_table, paired_tests_table);

fprintf("\nq=6方向约束搜索完成：%s\n", output_dir);
disp(summary_table(:, [ ...
    "GroupName", "Constrained_STRdB", ...
    "Constrained_FrOverBr", "Constrained_FaOverBa", ...
    "Constrained_TestPSNR", "Constrained_TestSSIM", ...
    "DeltaPSNR", "DeltaSSIM"]));
end


function experiment_cfg = buildExperimentConfig()
experiment_cfg = struct();
experiment_cfg.coarse_STR_dB = -10:4:10;
experiment_cfg.coarse_active_frequency = 0:0.4:2.4;
experiment_cfg.fine_STR_offsets = -2:1:2;
experiment_cfg.fine_frequency_offsets = -0.2:0.1:0.2;
experiment_cfg.max_refinement_rounds = 2;
experiment_cfg.max_parallel_workers = 8;
end


function validateSourceResult(loaded)
required_fields = [ ...
    "group_defs", "group_results", "sample_manifest", ...
    "calibration_indices", "test_indices", "signature"];
for idx = 1:numel(required_fields)
    assert(isfield(loaded, required_fields(idx)), ...
        "二维RSFT搜索结果缺少字段：%s", required_fields(idx));
end
assert(isfield(loaded.signature, "azimuth_bandwidth_Hz"), ...
    "二维RSFT搜索结果缺少方位带宽。");
end


function target_defs = buildTargetDefinitions(loaded)
group_names = string({loaded.group_defs.GroupName});
r6a1_idx = find(group_names == "R6A1");
r1a6_idx = find(group_names == "R1A6");
assert(isscalar(r6a1_idx) && isscalar(r1a6_idx), ...
    "二维RSFT搜索结果未唯一包含R6A1和R1A6。");

empty_target = struct( ...
    "GroupName", "", "ModelName", "", ...
    "ActiveDirection", "", "FixedFrOverBr", NaN, ...
    "FixedFaOverBa", NaN, "SourceGroupIdx", 0);
target_defs = repmat(empty_target, 2, 1);

target_defs(1) = struct( ...
    "GroupName", "R6A1", ...
    "ModelName", "Zhao fast-time RSFT", ...
    "ActiveDirection", "range", ...
    "FixedFrOverBr", NaN, ...
    "FixedFaOverBa", 0, ...
    "SourceGroupIdx", r6a1_idx);
target_defs(2) = struct( ...
    "GroupName", "R1A6", ...
    "ModelName", "Nie slow-time SFT", ...
    "ActiveDirection", "azimuth", ...
    "FixedFrOverBr", 0, ...
    "FixedFaOverBa", NaN, ...
    "SourceGroupIdx", r1a6_idx);
end


function validateUnconstrainedBaselines(target_defs, group_results)
expected = struct( ...
    "R6A1", [-4, 1.8, 0.7], ...
    "R1A6", [-4, 1.2, 1.6]);

for idx = 1:numel(target_defs)
    target = target_defs(idx);
    best = group_results{target.SourceGroupIdx}.best;
    actual = [best.STRdB, best.FrOverBr, best.FaOverBa];
    reference = expected.(target.GroupName);
    assert(max(abs(actual - reference)) < 1e-12, ...
        "%s无约束最优参数与预期基线不一致。", target.GroupName);
end
end


function validateSampleSplit( ...
        sample_manifest, calibration_indices, test_indices)
calibration_manifest = sample_manifest(calibration_indices, :);
test_manifest = sample_manifest(test_indices, :);
dataset_ids = unique(sample_manifest.DatasetIdx);

assert(numel(calibration_indices) == 35 && numel(test_indices) == 35, ...
    "校准集和测试集必须各包含35个样本。");
assert(all(mod(calibration_manifest.LocalSampleIdx, 2) == 1), ...
    "校准集中包含非奇数LocalSampleIdx。");
assert(all(mod(test_manifest.LocalSampleIdx, 2) == 0), ...
    "测试集中包含非偶数LocalSampleIdx。");

for idx = 1:numel(dataset_ids)
    dataset_idx = dataset_ids(idx);
    assert(sum(calibration_manifest.DatasetIdx == dataset_idx) == 5, ...
        "数据集%d的校准样本数不是5。", dataset_idx);
    assert(sum(test_manifest.DatasetIdx == dataset_idx) == 5, ...
        "数据集%d的测试样本数不是5。", dataset_idx);
end
end


function stage_result = runGridStage( ...
        group, target, stage_name, STR_dB_list, frequency_list, ...
        sample_cache, calibration_indices, S60, ...
        azimuth_bandwidth_Hz, num_workers, ...
        checkpoint_dir, group_signature)

STR_dB_list = unique(round(STR_dB_list(:).', 10));
frequency_list = unique(round(frequency_list(:).', 10));
assert(all(frequency_list >= 0), "活动频率比不能为负。");

checkpoint_path = fullfile(checkpoint_dir, ...
    sprintf("%s_%s.mat", target.GroupName, stage_name));
stage_signature = struct( ...
    "group_signature", group_signature, ...
    "stage_name", stage_name, ...
    "STR_dB_list", STR_dB_list, ...
    "frequency_list", frequency_list, ...
    "calibration_indices", calibration_indices(:).');

num_STR = numel(STR_dB_list);
num_frequency = numel(frequency_list);
num_samples = numel(calibration_indices);
num_configs = num_STR * num_frequency;

state = struct();
state.signature = stage_signature;
state.completed_samples = 0;
state.psnr_cube = nan(num_STR, num_frequency, num_samples);
state.ssim_cube = nan(num_STR, num_frequency, num_samples);

if isfile(checkpoint_path)
    loaded = load(checkpoint_path, "state");
    assert(isfield(loaded, "state") && ...
        isequaln(loaded.state.signature, stage_signature), ...
        "搜索检查点与当前配置不匹配：%s", checkpoint_path);
    state = loaded.state;
    fprintf("  %s：恢复检查点 %d/%d 个校准样本。\n", ...
        stage_name, state.completed_samples, num_samples);
end

fprintf("  %s：%d×%d=%d个参数点。\n", ...
    stage_name, num_STR, num_frequency, num_configs);

for local_sample_idx = state.completed_samples + 1:num_samples
    sample_idx = calibration_indices(local_sample_idx);
    signal_up = V4Core.twoDimUpsample( ...
        sample_cache(sample_idx).signal60_input, ...
        group.Azimuth_q, group.Range_q);
    img_gt = sample_cache(sample_idx).img_gt;

    psnr_values = nan(num_configs, 1);
    ssim_values = nan(num_configs, 1);
    current_STR = STR_dB_list;
    current_frequency = frequency_list;
    current_target = target;
    range_q = group.Range_q;
    azimuth_q = group.Azimuth_q;

    parfor (config_idx = 1:num_configs, num_workers)
        [str_idx, frequency_idx] = ind2sub( ...
            [num_STR, num_frequency], config_idx);
        [fr_over_Br, fa_over_Ba] = resolveFrequencies( ...
            current_target, current_frequency(frequency_idx)); %#ok<PFBNS>
        U = buildRSFT2DThreshold( ...
            signal_up, S60, range_q, azimuth_q, ...
            current_STR(str_idx), fr_over_Br, fa_over_Ba, ...
            azimuth_bandwidth_Hz); %#ok<PFBNS>
        channel_1bit = V4Core.quantizeWithThreshold(signal_up, U);
        img_out = V4Core.focusUpsampledChannel( ...
            channel_1bit, S60, range_q, azimuth_q);
        psnr_values(config_idx) = psnr(img_out, img_gt);
        ssim_values(config_idx) = ssim(img_out, img_gt);
    end

    state.psnr_cube(:, :, local_sample_idx) = ...
        reshape(psnr_values, [num_STR, num_frequency]);
    state.ssim_cube(:, :, local_sample_idx) = ...
        reshape(ssim_values, [num_STR, num_frequency]);
    state.completed_samples = local_sample_idx;
    save(checkpoint_path, "state", "-v7.3");

    fprintf("    %s：校准样本 %02d/%02d 完成。\n", ...
        stage_name, local_sample_idx, num_samples);
end

stage_result = summarizeGridStage(state, target);
end


function stage_result = summarizeGridStage(state, target)
assert(state.completed_samples == size(state.psnr_cube, 3), ...
    "参数搜索尚未完成全部校准样本。");

psnr_mean = mean(state.psnr_cube, 3, "omitnan");
ssim_mean = mean(state.ssim_cube, 3, "omitnan");
assert(all(isfinite(psnr_mean), "all") && ...
    all(isfinite(ssim_mean), "all"), ...
    "参数搜索指标中存在非有限值。");

STR_dB_list = state.signature.STR_dB_list;
frequency_list = state.signature.frequency_list;
[STR_grid, frequency_grid] = ndgrid(STR_dB_list, frequency_list);

[fr_grid, fa_grid] = resolveFrequencies(target, frequency_grid);
candidate_table = table( ...
    STR_grid(:), fr_grid(:), fa_grid(:), frequency_grid(:), ...
    psnr_mean(:), ssim_mean(:), abs(STR_grid(:)), ...
    'VariableNames', { ...
    'STRdB', 'FrOverBr', 'FaOverBa', 'ActiveFrequency', ...
    'PSNR_Mean', 'SSIM_Mean', 'AbsSTR'});
candidate_table = sortrows(candidate_table, ...
    {'SSIM_Mean', 'PSNR_Mean', 'AbsSTR', 'ActiveFrequency'}, ...
    {'descend', 'descend', 'ascend', 'ascend'});

best_row = candidate_table(1, :);
str_idx = nearestIndex(STR_dB_list, best_row.STRdB);
frequency_idx = nearestIndex( ...
    frequency_list, best_row.ActiveFrequency);

touches_STR = str_idx == 1 || str_idx == numel(STR_dB_list);
touches_frequency = ...
    frequency_idx == 1 || frequency_idx == numel(frequency_list);
expandable_frequency = ...
    frequency_idx == numel(frequency_list) || ...
    (frequency_idx == 1 && min(frequency_list) > 0);

best = struct( ...
    "STRdB", best_row.STRdB, ...
    "FrOverBr", best_row.FrOverBr, ...
    "FaOverBa", best_row.FaOverBa, ...
    "ActiveFrequency", best_row.ActiveFrequency, ...
    "PSNR_Mean", best_row.PSNR_Mean, ...
    "SSIM_Mean", best_row.SSIM_Mean);

stage_result = struct();
stage_result.signature = state.signature;
stage_result.best = best;
stage_result.grid_table = removevars(candidate_table, "AbsSTR");
stage_result.psnr_cube = state.psnr_cube;
stage_result.ssim_cube = state.ssim_cube;
stage_result.TouchesSTRBoundary = touches_STR;
stage_result.TouchesFrequencyBoundary = touches_frequency;
stage_result.TouchesBoundary = touches_STR || touches_frequency;
stage_result.TouchesExpandableBoundary = ...
    touches_STR || expandable_frequency;
end


function idx = nearestIndex(values, target)
[distance, idx] = min(abs(values - target));
assert(distance < 1e-9, "无法在参数网格中定位最优值。");
end


function [fine_STR, fine_frequency] = ...
        buildFineGrid(best, experiment_cfg)
fine_STR = best.STRdB + experiment_cfg.fine_STR_offsets;
fine_frequency = ...
    best.ActiveFrequency + experiment_cfg.fine_frequency_offsets;
fine_frequency = fine_frequency(fine_frequency >= 0);
fine_STR = unique(round(fine_STR, 10));
fine_frequency = unique(round(fine_frequency, 10));
end


function test_result = evaluateLockedParameters( ...
        group, target, best, sample_cache, test_indices, S60, ...
        azimuth_bandwidth_Hz, checkpoint_dir, group_signature)

checkpoint_path = fullfile(checkpoint_dir, ...
    target.GroupName + "_test.mat");
test_signature = struct( ...
    "group_signature", group_signature, ...
    "STRdB", best.STRdB, ...
    "FrOverBr", best.FrOverBr, ...
    "FaOverBa", best.FaOverBa, ...
    "test_indices", test_indices(:).');

num_samples = numel(test_indices);
state = struct();
state.signature = test_signature;
state.completed_samples = 0;
state.PSNR = nan(num_samples, 1);
state.SSIM = nan(num_samples, 1);

if isfile(checkpoint_path)
    loaded = load(checkpoint_path, "state");
    assert(isfield(loaded, "state") && ...
        isequaln(loaded.state.signature, test_signature), ...
        "测试检查点与当前配置不匹配：%s", checkpoint_path);
    state = loaded.state;
    fprintf("  test：恢复检查点 %d/%d。\n", ...
        state.completed_samples, num_samples);
end

for local_idx = state.completed_samples + 1:num_samples
    sample_idx = test_indices(local_idx);
    signal_up = V4Core.twoDimUpsample( ...
        sample_cache(sample_idx).signal60_input, ...
        group.Azimuth_q, group.Range_q);
    U = buildRSFT2DThreshold( ...
        signal_up, S60, group.Range_q, group.Azimuth_q, ...
        best.STRdB, best.FrOverBr, best.FaOverBa, ...
        azimuth_bandwidth_Hz);
    channel_1bit = V4Core.quantizeWithThreshold(signal_up, U);
    img_out = V4Core.focusUpsampledChannel( ...
        channel_1bit, S60, group.Range_q, group.Azimuth_q);
    img_gt = sample_cache(sample_idx).img_gt;

    state.PSNR(local_idx) = psnr(img_out, img_gt);
    state.SSIM(local_idx) = ssim(img_out, img_gt);
    state.completed_samples = local_idx;
    save(checkpoint_path, "state", "-v7.3");
end

assert(all(isfinite(state.PSNR)) && all(isfinite(state.SSIM)), ...
    "约束最优测试指标中存在非有限值。");
test_result = struct( ...
    "signature", test_signature, ...
    "PSNR", state.PSNR, ...
    "SSIM", state.SSIM);
end


function validateBaselineTestOrder(test_result, test_indices)
assert(isfield(test_result, "signature") && ...
    isfield(test_result.signature, "test_indices"), ...
    "无约束测试结果缺少测试样本顺序。");
assert(isequal(test_result.signature.test_indices(:), test_indices(:)), ...
    "无约束测试结果与方向约束实验的样本顺序不一致。");
assert(all(isfinite(test_result.PSNR)) && ...
    all(isfinite(test_result.SSIM)), ...
    "无约束测试指标中存在非有限值。");
end


function [summary_table, detail_table, search_grid_table, paired_tests] = ...
        aggregateResults(target_results, sample_manifest, test_indices)

num_targets = numel(target_results);
num_test = numel(test_indices);
summary_rows = cell(num_targets, 1);
detail_rows = cell(num_targets, 1);
grid_rows = cell(0, 1);
paired_rows = cell(num_targets, 1);
grid_ptr = 0;
test_manifest = sample_manifest(test_indices, :);

for target_idx = 1:num_targets
    result = target_results{target_idx};
    constrained = result.constrained_test;
    unconstrained = result.unconstrained_test;
    delta_psnr = constrained.PSNR - unconstrained.PSNR;
    delta_ssim = constrained.SSIM - unconstrained.SSIM;
    [p_psnr, p_ssim] = pairedPValues( ...
        constrained, unconstrained);

    summary_rows{target_idx} = table( ...
        string(result.target.GroupName), ...
        string(result.target.ModelName), ...
        result.group.Range_q, result.group.Azimuth_q, ...
        result.best.STRdB, result.best.FrOverBr, result.best.FaOverBa, ...
        result.best.PSNR_Mean, result.best.SSIM_Mean, ...
        mean(constrained.PSNR), std(constrained.PSNR, 0), ...
        mean(constrained.SSIM), std(constrained.SSIM, 0), ...
        result.unconstrained_best.STRdB, ...
        result.unconstrained_best.FrOverBr, ...
        result.unconstrained_best.FaOverBa, ...
        mean(unconstrained.PSNR), mean(unconstrained.SSIM), ...
        mean(delta_psnr), mean(delta_ssim), ...
        'VariableNames', { ...
        'GroupName', 'DirectionalModel', 'Range_q', 'Azimuth_q', ...
        'Constrained_STRdB', 'Constrained_FrOverBr', ...
        'Constrained_FaOverBa', ...
        'Calibration_PSNR_Mean', 'Calibration_SSIM_Mean', ...
        'Constrained_TestPSNR', 'Constrained_TestPSNR_Std', ...
        'Constrained_TestSSIM', 'Constrained_TestSSIM_Std', ...
        'Unconstrained_STRdB', 'Unconstrained_FrOverBr', ...
        'Unconstrained_FaOverBa', ...
        'Unconstrained_TestPSNR', 'Unconstrained_TestSSIM', ...
        'DeltaPSNR', 'DeltaSSIM'});

    detail_rows{target_idx} = table( ...
        repmat(string(result.target.GroupName), num_test, 1), ...
        repmat(string(result.target.ModelName), num_test, 1), ...
        test_manifest.SampleID, test_manifest.DatasetIdx, ...
        test_manifest.LocalSampleIdx, test_manifest.Dataset, ...
        test_manifest.File, test_manifest.CStart, ...
        repmat(result.best.STRdB, num_test, 1), ...
        repmat(result.best.FrOverBr, num_test, 1), ...
        repmat(result.best.FaOverBa, num_test, 1), ...
        constrained.PSNR, constrained.SSIM, ...
        unconstrained.PSNR, unconstrained.SSIM, ...
        delta_psnr, delta_ssim, ...
        'VariableNames', { ...
        'GroupName', 'DirectionalModel', ...
        'SampleID', 'DatasetIdx', 'LocalSampleIdx', ...
        'Dataset', 'File', 'CStart', ...
        'Constrained_STRdB', 'Constrained_FrOverBr', ...
        'Constrained_FaOverBa', ...
        'Constrained_PSNR', 'Constrained_SSIM', ...
        'Unconstrained_PSNR', 'Unconstrained_SSIM', ...
        'DeltaPSNR', 'DeltaSSIM'});

    paired_rows{target_idx} = table( ...
        string(result.target.GroupName), ...
        mean(delta_psnr), mean(delta_ssim), p_psnr, p_ssim, ...
        'VariableNames', { ...
        'GroupName', 'DeltaPSNR', 'DeltaSSIM', ...
        'PValuePSNR', 'PValueSSIM'});

    for stage_idx = 1:numel(result.stage_results)
        stage = result.stage_results{stage_idx};
        rows = stage.grid_table;
        row_count = height(rows);
        prefix = table( ...
            repmat(string(result.target.GroupName), row_count, 1), ...
            repmat(string(result.target.ModelName), row_count, 1), ...
            repmat(string(stage.signature.stage_name), row_count, 1), ...
            'VariableNames', { ...
            'GroupName', 'DirectionalModel', 'SearchStage'});
        grid_ptr = grid_ptr + 1;
        grid_rows{grid_ptr, 1} = [prefix, rows];
    end
end

summary_table = vertcat(summary_rows{:});
detail_table = vertcat(detail_rows{:});
search_grid_table = vertcat(grid_rows{:});
paired_tests = vertcat(paired_rows{:});
end


