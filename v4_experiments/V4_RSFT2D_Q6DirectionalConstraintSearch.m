function representative_images = buildRepresentativeImages( ...
        target_results, sample_cache, sample_manifest, ...
        test_indices, S60, azimuth_bandwidth_Hz)

test_manifest = sample_manifest(test_indices, :);
representative_local_indices = find(test_manifest.LocalSampleIdx == 2);
assert(numel(representative_local_indices) == 7, ...
    "每个数据集必须恰有一个LocalSampleIdx=2代表样本。");

representative_images = cell(numel(target_results), 1);
for target_idx = 1:numel(target_results)
    result = target_results{target_idx};
    num_representatives = numel(representative_local_indices);
    images = repmat(struct( ...
        "Dataset", "", "SampleID", 0, "GT", [], ...
        "Unconstrained", [], "Constrained", [], ...
        "UnconstrainedPSNR", NaN, "UnconstrainedSSIM", NaN, ...
        "ConstrainedPSNR", NaN, "ConstrainedSSIM", NaN), ...
        num_representatives, 1);

    for representative_idx = 1:num_representatives
        test_local_idx = representative_local_indices(representative_idx);
        sample_idx = test_indices(test_local_idx);
        signal_up = V4Core.twoDimUpsample( ...
            sample_cache(sample_idx).signal60_input, ...
            result.group.Azimuth_q, result.group.Range_q);
        img_gt = sample_cache(sample_idx).img_gt;
        img_unconstrained = reconstructWithParameters( ...
            signal_up, S60, result.group, ...
            result.unconstrained_best, azimuth_bandwidth_Hz);
        img_constrained = reconstructWithParameters( ...
            signal_up, S60, result.group, ...
            result.best, azimuth_bandwidth_Hz);

        assert(abs(psnr(img_unconstrained, img_gt) - ...
            result.unconstrained_test.PSNR(test_local_idx)) < 1e-9 && ...
            abs(ssim(img_unconstrained, img_gt) - ...
            result.unconstrained_test.SSIM(test_local_idx)) < 1e-9, ...
            "代表样本的无约束重建与已有测试指标不一致。");

        images(representative_idx) = struct( ...
            "Dataset", test_manifest.Dataset(test_local_idx), ...
            "SampleID", test_manifest.SampleID(test_local_idx), ...
            "GT", img_gt, ...
            "Unconstrained", img_unconstrained, ...
            "Constrained", img_constrained, ...
            "UnconstrainedPSNR", ...
            result.unconstrained_test.PSNR(test_local_idx), ...
            "UnconstrainedSSIM", ...
            result.unconstrained_test.SSIM(test_local_idx), ...
            "ConstrainedPSNR", ...
            result.constrained_test.PSNR(test_local_idx), ...
            "ConstrainedSSIM", ...
            result.constrained_test.SSIM(test_local_idx));
    end
    representative_images{target_idx} = images;
end
end


function img_out = reconstructWithParameters( ...
        signal_up, S60, group, params, azimuth_bandwidth_Hz)
U = buildRSFT2DThreshold( ...
    signal_up, S60, group.Range_q, group.Azimuth_q, ...
    params.STRdB, params.FrOverBr, params.FaOverBa, ...
    azimuth_bandwidth_Hz);
channel_1bit = V4Core.quantizeWithThreshold(signal_up, U);
img_out = V4Core.focusUpsampledChannel( ...
    channel_1bit, S60, group.Range_q, group.Azimuth_q);
end


function [fr_over_Br, fa_over_Ba] = ...
        resolveFrequencies(target, active_frequency)
if target.ActiveDirection == "range"
    fr_over_Br = active_frequency;
    fa_over_Ba = zeros(size(active_frequency));
elseif target.ActiveDirection == "azimuth"
    fr_over_Br = zeros(size(active_frequency));
    fa_over_Ba = active_frequency;
else
    error("未知活动频率方向：%s", target.ActiveDirection);
end
end


function U = buildRSFT2DThreshold( ...
        signal_up, S60, range_q, azimuth_q, ...
        STR_dB, fr_over_Br, fa_over_Ba, azimuth_bandwidth_Hz)
% 与完整二维搜索一致的恒模距离-方位相位和阈值。

[Nr_up, Na_up] = size(signal_up);
fast_time_rel = ...
    ((0:Nr_up - 1).' - floor(Nr_up / 2)) / (range_q * S60.Fs);
slow_time_rel = ...
    ((0:Na_up - 1) - floor(Na_up / 2)) / (azimuth_q * S60.prf);

fr_Hz = fr_over_Br * S60.B;
fa_Hz = fa_over_Ba * azimuth_bandwidth_Hz;
sigma_hat = sqrt(2 / pi) * mean(abs(signal_up(:)));
threshold_amplitude = sigma_hat / (10 ^ (STR_dB / 20));

phase_range = 2 * pi * fr_Hz * fast_time_rel;
phase_azimuth = 2 * pi * fa_Hz * slow_time_rel;
U = threshold_amplitude * exp(1i * (phase_range + phase_azimuth));
end


