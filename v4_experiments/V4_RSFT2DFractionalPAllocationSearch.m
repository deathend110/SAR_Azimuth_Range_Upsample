function [summary_table, detail_table, search_grid_table, ...
        test_psnr_all, test_ssim_all] = aggregateResults( ...
        group_results, group_defs, sample_manifest, test_indices)
num_groups = numel(group_results);
num_test = numel(test_indices);
summary_rows = cell(num_groups, 1);
detail_rows = cell(num_groups, 1);
grid_rows = cell(0, 1);
grid_ptr = 0;
test_psnr_all = nan(num_groups, num_test);
test_ssim_all = nan(num_groups, num_test);
test_manifest = sample_manifest(test_indices, :);

for group_idx = 1:num_groups
    result = group_results{group_idx};
    current = group_defs(group_idx);
    summary_rows{group_idx} = result.summary_row;
    test_psnr_all(group_idx, :) = result.test_result.PSNR.';
    test_ssim_all(group_idx, :) = result.test_result.SSIM.';

    detail_rows{group_idx} = table( ...
        repmat(current.PIndex, num_test, 1), ...
        repmat(current.PLabel, num_test, 1), ...
        repmat(current.P, num_test, 1), ...
        repmat(current.P2, num_test, 1), ...
        repmat(current.GroupName, num_test, 1), ...
        repmat(current.Range_q, num_test, 1), ...
        repmat(current.Azimuth_q, num_test, 1), ...
        repmat(current.GroupType, num_test, 1), ...
        repmat(result.best.STRdB, num_test, 1), ...
        repmat(result.best.FrOverBr, num_test, 1), ...
        repmat(result.best.FaOverBa, num_test, 1), ...
        test_manifest.SampleID, test_manifest.DatasetIdx, ...
        test_manifest.LocalSampleIdx, test_manifest.Dataset, ...
        test_manifest.File, test_manifest.CStart, ...
        result.test_result.PSNR, result.test_result.SSIM, ...
        'VariableNames', { ...
        'PIndex', 'PLabel', 'P', 'P2', ...
        'GroupName', 'Range_q', 'Azimuth_q', 'GroupType', ...
        'STRdB', 'FrOverBr', 'FaOverBa', ...
        'SampleID', 'DatasetIdx', 'LocalSampleIdx', ...
        'Dataset', 'File', 'CStart', 'PSNR', 'SSIM'});

    for stage_idx = 1:numel(result.stage_results)
        stage = result.stage_results{stage_idx};
        rows = stage.grid_table;
        row_count = height(rows);
        prefix = table( ...
            repmat(current.PIndex, row_count, 1), ...
            repmat(current.PLabel, row_count, 1), ...
            repmat(current.P, row_count, 1), ...
            repmat(current.P2, row_count, 1), ...
            repmat(current.GroupName, row_count, 1), ...
            repmat(current.Range_q, row_count, 1), ...
            repmat(current.Azimuth_q, row_count, 1), ...
            repmat(current.GroupType, row_count, 1), ...
            repmat(string(stage.signature.stage_name), row_count, 1), ...
            'VariableNames', { ...
            'PIndex', 'PLabel', 'P', 'P2', ...
            'GroupName', 'Range_q', 'Azimuth_q', ...
            'GroupType', 'SearchStage'});
        grid_ptr = grid_ptr + 1;
        grid_rows{grid_ptr, 1} = [prefix, rows];
    end
end
summary_table = vertcat(summary_rows{:});
detail_table = vertcat(detail_rows{:});
search_grid_table = vertcat(grid_rows{:});
end


function budget_best_table = buildBudgetBest(summary_table)
p_indices = unique(summary_table.PIndex);
num_p = numel(p_indices);
rows = cell(num_p, 1);
for idx = 1:num_p
    candidates = summary_table(summary_table.PIndex == p_indices(idx), :);
    candidates = sortrows(candidates, ...
        {'Test_SSIM_Mean', 'Test_PSNR_Mean', ...
        'Best_FrOverBr', 'Best_FaOverBa'}, ...
        {'descend', 'descend', 'ascend', 'ascend'});
    best = candidates(1, :);
    rows{idx} = table( ...
        best.PIndex, best.PLabel, best.P, best.P2, ...
        best.GroupName, best.Range_q, best.Azimuth_q, ...
        best.GroupType == "balanced", ...
        best.Best_STRdB, best.Best_FrOverBr, best.Best_FaOverBa, ...
        best.Test_PSNR_Mean, best.Test_SSIM_Mean, ...
        'VariableNames', { ...
        'PIndex', 'PLabel', 'P', 'P2', ...
        'BestAllocation', 'BestRangeQ', 'BestAzimuthQ', ...
        'IsBalanced', 'BestSTRdB', 'BestFrOverBr', ...
        'BestFaOverBa', 'BestTestPSNR', 'BestTestSSIM'});
end
budget_best_table = vertcat(rows{:});
end


function paired_tests = buildPairedTests( ...
        group_defs, summary_table, test_psnr_all, test_ssim_all)
p_indices = unique(summary_table.PIndex);
rows = cell(numel(p_indices), 1);
for idx = 1:numel(p_indices)
    p_idx = p_indices(idx);
    group_indices = find([group_defs.PIndex].' == p_idx);
    group_types = string({group_defs(group_indices).GroupType}).';
    balanced_idx = group_indices(group_types == "balanced");
    unidirectional_indices = group_indices( ...
        ismember(group_types, ["range_only", "azimuth_only"]));
    assert(isscalar(balanced_idx) && ...
        numel(unidirectional_indices) == 2, ...
        "每个p必须包含一组均衡分配和两组单向分配。");

    unidirectional_rows = summary_table(unidirectional_indices, :);
    unidirectional_rows = sortrows(unidirectional_rows, ...
        {'Test_SSIM_Mean', 'Test_PSNR_Mean'}, ...
        {'descend', 'descend'});
    best_unidirectional_name = unidirectional_rows.GroupName(1);
    best_unidirectional_idx = find( ...
        summary_table.GroupName == best_unidirectional_name & ...
        summary_table.PIndex == p_idx, 1);

    delta_psnr = ...
        test_psnr_all(balanced_idx, :) - ...
        test_psnr_all(best_unidirectional_idx, :);
    delta_ssim = ...
        test_ssim_all(balanced_idx, :) - ...
        test_ssim_all(best_unidirectional_idx, :);
    if exist("signrank", "file") == 2
        p_psnr = signrank( ...
            test_psnr_all(balanced_idx, :), ...
            test_psnr_all(best_unidirectional_idx, :), ...
            "tail", "both");
        p_ssim = signrank( ...
            test_ssim_all(balanced_idx, :), ...
            test_ssim_all(best_unidirectional_idx, :), ...
            "tail", "both");
    else
        p_psnr = NaN;
        p_ssim = NaN;
    end

    reference = summary_table(balanced_idx, :);
    rows{idx} = table( ...
        reference.PIndex, reference.PLabel, reference.P, reference.P2, ...
        reference.GroupName, best_unidirectional_name, ...
        mean(delta_psnr), mean(delta_ssim), p_psnr, p_ssim, ...
        'VariableNames', { ...
        'PIndex', 'PLabel', 'P', 'P2', ...
        'BalancedGroup', 'BestUnidirectionalGroup', ...
        'DeltaPSNR', 'DeltaSSIM', 'PValuePSNR', 'PValueSSIM'});
end
paired_tests = vertcat(rows{:});
end


