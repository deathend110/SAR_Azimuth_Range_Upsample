    height(signature.sample_manifest));
fprintf(fid, "ENLSampleCount=%d\n", ...
    height(signature.roi_manifest));
fprintf(fid, "EntropyBins=%d\n", ...
    signature.entropy_num_bins);
fprintf(fid, "ENLWindow=%d\n", ...
    signature.enl_window_size);
fprintf(fid, "ENLStride=%d\n", ...
    signature.enl_stride);
