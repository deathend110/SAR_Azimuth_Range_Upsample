candidates = summary_table(:, [ ...
    "Q", "GroupName", "Range_q", "Azimuth_q", "GroupType", ...
    "SampleCount", "ENLSampleCount", "As", ...
    "PSNR_Mean", "PSNR_Std", "SSIM_Mean", "SSIM_Std", ...
    "Entropy_Mean", "Entropy_Std", "ENL_Mean", "ENL_Std"]);
end


function validateResults( ...
        cfg, main_dir, group_defs, sample_manifest, ...
        summary_table, detail_table, paired_tests_table, ...
        psnr_all, ssim_all, entropy_all, enl_all)
num_groups = numel(group_defs);
total_samples = height(sample_manifest);
num_p = numel(unique([group_defs.PIndex]));
expected_num_groups = 3 * num_p;
assert(num_groups == expected_num_groups && ...
    height(summary_table) == expected_num_groups, ...
    "RT小数p实验应包含%d个组。", expected_num_groups);
assert(height(detail_table) == num_groups * total_samples && ...
    total_samples == 70, ...
    "RT小数p逐样本明细应包含%d行。", ...
    expected_num_groups * 70);
assert(height(paired_tests_table) == num_p, ...
    "RT小数p配对检验应包含%d行。", num_p);
assert(all(summary_table.SampleCount == total_samples) && ...
    all(summary_table.ENLSampleCount == 20), ...
    "样本数或ENL样本数与Table III(a)不一致。");
assert(all(isfinite(psnr_all), "all") && ...
    all(isfinite(ssim_all), "all") && ...
    all(isfinite(entropy_all), "all") && ...
    all(isfinite(enl_all(~isnan(enl_all)))), ...
    "RT小数p实验存在非有限指标。");
assert(all(summary_table.Entropy_Mean >= 0 & ...
    summary_table.Entropy_Mean <= log2(cfg.entropy_num_bins)) && ...
    all(summary_table.ENL_Mean > 0), ...
    "Entropy或ENL超出有效范围。");

main_detail_path = fullfile(main_dir, "V4_Main_Detail.csv");
if ~isfile(main_detail_path)
    warning("V4:ReferenceRegressionSkipped", ...
        "缺少Table III(a)逐样本结果，跳过重合组数值回归。");
    return;
end
main_detail = readtable( ...
    main_detail_path, "TextType", "string");
duplicate_names = intersect( ...
    string({group_defs.GroupName}), ...
    unique(main_detail.GroupName, "stable"), "stable");
if isempty(duplicate_names)
    warning("V4:ReferenceRegressionSkipped", ...
        "小数p实验与Table III(a)之间不存在可回归的重合组。");
    return;
end
metric_names = ["PSNR", "SSIM", "Entropy"];
% FFT浮点舍入可能使极少量1-bit符号判决翻转，不能要求跨次运行逐位相等。
% 参考结果回归仅用于提示潜在漂移，不影响本次有效结果保存。
metric_tolerances = [1e-3, 2e-5, 2e-4];
enl_tolerance = 1e-6;
for name = duplicate_names(:).'
    new_idx = find(string({group_defs.GroupName}) == name, 1);
    old_rows = main_detail(main_detail.GroupName == name, :);
    old_rows = sortrows(old_rows, "SampleID");
    if height(old_rows) ~= total_samples || ...
            ~isequal(old_rows.SampleID, sample_manifest.SampleID)
        warning("V4:ReferenceRegressionSkipped", ...
            "%s的Table III(a)逐样本清单不一致，跳过该组数值回归。", ...
            name);
        continue;
    end

    new_metrics = [ ...
        psnr_all(new_idx, :).', ...
        ssim_all(new_idx, :).', ...
        entropy_all(new_idx, :).'];
    for metric_idx = 1:numel(metric_names)
        metric_name = metric_names(metric_idx);
        old_values = old_rows.(metric_name);
        max_difference = max(abs( ...
            old_values - new_metrics(:, metric_idx)));
        if max_difference > metric_tolerances(metric_idx)
            warning("V4:ReferenceRegressionDrift", ...
                "%s的%s相对Table III(a)存在数值漂移：" + ...
                "最大差值%.6g，参考容差%.6g。", ...
                name, metric_name, max_difference, ...
                metric_tolerances(metric_idx));
        end
    end

    enl_mask = isfinite(old_rows.ENL);
    if ~isequal(enl_mask, isfinite(enl_all(new_idx, :).'))
        warning("V4:ReferenceRegressionSkipped", ...
            "%s的Table III(a) ENL样本掩膜不一致，跳过ENL数值回归。", ...
            name);
        continue;
    end
    max_enl_difference = max(abs( ...
        old_rows.ENL(enl_mask) - ...
        enl_all(new_idx, enl_mask).'));
    if max_enl_difference > enl_tolerance
        warning("V4:ReferenceRegressionDrift", ...
            "%s的ENL相对Table III(a)存在数值漂移：" + ...
            "最大差值%.6g，参考容差%.6g。", ...
            name, max_enl_difference, enl_tolerance);
    end
end
end


function writeMetadata( ...
        output_dir, signature, summary_table, paired_tests_table)
metadata_path = fullfile(output_dir, ...
    "RTFractionalP_Metadata.txt");
fid = fopen(metadata_path, "w");
assert(fid >= 0, "无法创建metadata文件：%s", metadata_path);
cleanup = onCleanup(@() fclose(fid));

fprintf(fid, "Experiment=%s\n", signature.experiment);
fprintf(fid, "Seed=%d\n", signature.seed);
fprintf(fid, "As=%.16g\n", signature.As);
