function paired_tests = buildPairedTests( ...
        group_defs, summary_table, psnr_all, ssim_all)
p_indices = unique(summary_table.PIndex);
rows = cell(numel(p_indices), 1);
for idx = 1:numel(p_indices)
    p_idx = p_indices(idx);
    group_indices = find([group_defs.PIndex].' == p_idx);
    group_types = string({group_defs(group_indices).GroupType}).';
    balanced_idx = group_indices(group_types == "balanced");
    unidirectional_indices = group_indices( ...
        ismember(group_types, ["range_only", "azimuth_only"]));
    assert(isscalar(balanced_idx) && ...
        numel(unidirectional_indices) == 2, ...
        "每个p必须包含一组平衡分配和两组单向分配。");

    [~, best_local_idx] = max( ...
        summary_table.PSNR_Mean(unidirectional_indices));
    best_unidirectional_idx = ...
        unidirectional_indices(best_local_idx);
    delta_psnr = ...
        psnr_all(balanced_idx, :) - ...
        psnr_all(best_unidirectional_idx, :);
    delta_ssim = ...
        ssim_all(balanced_idx, :) - ...
        ssim_all(best_unidirectional_idx, :);
    p_psnr = signrank( ...
        psnr_all(balanced_idx, :), ...
        psnr_all(best_unidirectional_idx, :), "tail", "both");
    p_ssim = signrank( ...
        ssim_all(balanced_idx, :), ...
        ssim_all(best_unidirectional_idx, :), "tail", "both");

    reference = summary_table(balanced_idx, :);
    delta_psnr_mean = mean(delta_psnr);
    delta_ssim_mean = mean(delta_ssim);
    metrics_finite = all(isfinite([ ...
        reference.Entropy_Mean, reference.ENL_Mean]));
    suitable = delta_psnr_mean > 0 && delta_ssim_mean > 0 && ...
        p_psnr < 0.05 && p_ssim < 0.05 && metrics_finite;

    rows{idx} = table( ...
        reference.PIndex, reference.PLabel, ...
        reference.P, reference.P2, ...
        reference.GroupName, ...
        summary_table.GroupName(best_unidirectional_idx), ...
        delta_psnr_mean, delta_ssim_mean, ...
        p_psnr, p_ssim, metrics_finite, suitable, ...
        'VariableNames', { ...
        'PIndex', 'PLabel', 'P', 'P2', ...
        'BalancedGroup', 'BestUnidirectionalGroup', ...
        'DeltaPSNR', 'DeltaSSIM', ...
        'PValuePSNR', 'PValueSSIM', ...
        'MetricsFinite', 'SuitableByDefaultRule'});
end
paired_tests = vertcat(rows{:});
end


