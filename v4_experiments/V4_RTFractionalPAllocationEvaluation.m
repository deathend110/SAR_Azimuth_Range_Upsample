function V4_RTFractionalPAllocationEvaluation()
% 使用Table III(a)的固定SplitRT协议评价小数p分配。

cfg = V4Core.config();
assert(abs(cfg.As - 0.6) < 1e-12, ...
    "本实验要求与Table III(a)一致，必须固定As=0.6。");

addpath(cfg.repo_root, cfg.experiment_dir);
output_dir = fullfile( ...
    cfg.output_root, "RTFractionalPAllocationEvaluation");
p_values = [1.5, sqrt(3), 2.5, sqrt(6), sqrt(8), sqrt(10)];
p_labels = ["1.5", "sqrt3", "2.5", "sqrt6", "sqrt8", "sqrt10"];
checkpoint_set_key = "P_" + strjoin( ...
    replace(p_labels, ".", "p"), "_");
checkpoint_root = fullfile(output_dir, "Checkpoints");
checkpoint_dir = fullfile(checkpoint_root, checkpoint_set_key);
main_dir = fullfile(cfg.output_root, "MainEvaluation");
V4Core.ensureDir(cfg.output_root);
V4Core.ensureDir(output_dir);
V4Core.ensureDir(checkpoint_root);
V4Core.ensureDir(checkpoint_dir);

S60 = load(cfg.parameter_file);
[sample_cache, sample_manifest] = V4Core.buildSampleCache(cfg, S60);
[roi_manifest, is_enl_sample, enl_top, enl_left] = ...
    loadAndValidateMainProtocol( ...
    main_dir, sample_manifest, cfg.enl_window_size);

base_group_defs = V4Core.buildGroupDefinitions(cfg.Q_list);
group_defs = buildGroupDefinitions( ...
    p_values, p_labels, base_group_defs);
signature = buildSignature( ...
    cfg, p_values, p_labels, group_defs, ...
    sample_manifest, roi_manifest);

num_groups = numel(group_defs);
total_samples = numel(sample_cache);
psnr_all = nan(num_groups, total_samples);
ssim_all = nan(num_groups, total_samples);
entropy_all = nan(num_groups, total_samples);
enl_all = nan(num_groups, total_samples);

fprintf("\n=== RT小数p分配实验：%d组 × %d样本 ===\n", ...
    num_groups, total_samples);
fprintf("SplitRT：As=%.1f，seed=%d，不搜索阈值参数。\n", ...
    cfg.As, cfg.seed);

for group_idx = 1:num_groups
    current = group_defs(group_idx);
    fprintf("\n[%02d/%02d] %s（R=%.15g，A=%.15g，RNG组=%d）\n", ...
        group_idx, num_groups, current.GroupName, ...
        current.Range_q, current.Azimuth_q, ...
        current.RNGGroupIndex);

    checkpoint_path = fullfile( ...
        checkpoint_dir, current.FileKey + ".mat");
    state = evaluateGroup( ...
        current, signature, checkpoint_path, ...
        sample_cache, is_enl_sample, enl_top, enl_left, ...
        S60, cfg);

    psnr_all(group_idx, :) = state.PSNR.';
    ssim_all(group_idx, :) = state.SSIM.';
    entropy_all(group_idx, :) = state.Entropy.';
    enl_all(group_idx, :) = state.ENL.';
end

summary_table = buildSummaryTable( ...
    group_defs, cfg.As, ...
    psnr_all, ssim_all, entropy_all, enl_all);
detail_table = buildDetailTable( ...
    group_defs, sample_manifest, cfg.As, ...
    psnr_all, ssim_all, entropy_all, enl_all);
paired_tests_table = buildPairedTests( ...
    group_defs, summary_table, psnr_all, ssim_all);
table_iii_candidates = buildTableIIICandidates(summary_table);

validateResults( ...
    cfg, main_dir, group_defs, sample_manifest, ...
    summary_table, detail_table, paired_tests_table, ...
    psnr_all, ssim_all, entropy_all, enl_all);

summary_path = fullfile(output_dir, ...
    "RTFractionalP_GroupSummary.csv");
detail_path = fullfile(output_dir, ...
    "RTFractionalP_Detail.csv");
paired_path = fullfile(output_dir, ...
    "RTFractionalP_PairedTests.csv");
candidate_path = fullfile(output_dir, ...
    "RTFractionalP_TableIII_Candidates.csv");
data_path = fullfile(output_dir, ...
    "RTFractionalP_AllData.mat");

writetable(summary_table, summary_path);
writetable(detail_table, detail_path);
writetable(paired_tests_table, paired_path);
writetable(table_iii_candidates, candidate_path);
save(data_path, ...
    "cfg", "signature", "group_defs", ...
    "sample_manifest", "roi_manifest", ...
    "psnr_all", "ssim_all", "entropy_all", "enl_all", ...
    "summary_table", "detail_table", ...
    "paired_tests_table", "table_iii_candidates", "-v7.3");
writeMetadata( ...
    output_dir, signature, summary_table, paired_tests_table);

fprintf("\nRT小数p分配实验完成：%s\n", output_dir);
disp(summary_table(:, [ ...
    "PLabel", "GroupName", "Range_q", "Azimuth_q", ...
    "PSNR_Mean", "SSIM_Mean", "ENL_Mean", "Entropy_Mean"]));
disp(paired_tests_table);
end


function [roi_manifest, is_enl_sample, enl_top, enl_left] = ...
        loadAndValidateMainProtocol( ...
        main_dir, sample_manifest, expected_window_size)
sample_path = fullfile(main_dir, "V4_SampleManifest.csv");
roi_path = fullfile(main_dir, "V4_ENL_ROI_Manifest.csv");
assert(isfile(sample_path) && isfile(roi_path), ...
    "缺少Table III(a)样本或ENL ROI清单，请先运行V4_MainEvaluation。");

main_sample_manifest = readtable( ...
    sample_path, "TextType", "string");
roi_manifest = readtable( ...
    roi_path, "TextType", "string");
assert(isequaln(sample_manifest, main_sample_manifest), ...
    "当前样本清单与Table III(a)不一致。");

total_samples = height(sample_manifest);
[found, sample_rows] = ismember( ...
    roi_manifest.SampleID, sample_manifest.SampleID);
assert(all(found), "ENL ROI清单包含未知样本。");
assert(all(roi_manifest.DatasetIdx == ...
    sample_manifest.DatasetIdx(sample_rows)) && ...
    all(roi_manifest.LocalSampleIdx == ...
    sample_manifest.LocalSampleIdx(sample_rows)) && ...
    all(roi_manifest.Dataset == ...
    sample_manifest.Dataset(sample_rows)) && ...
    all(roi_manifest.File == ...
    sample_manifest.File(sample_rows)) && ...
    all(roi_manifest.CStart == ...
    sample_manifest.CStart(sample_rows)), ...
    "ENL ROI清单与样本顺序或来源不一致。");
assert(all(roi_manifest.ROIHeight == expected_window_size) && ...
    all(roi_manifest.ROIWidth == expected_window_size), ...
    "ENL ROI窗口尺寸与Table III(a)不一致。");

is_enl_sample = false(total_samples, 1);
enl_top = zeros(total_samples, 1);
enl_left = zeros(total_samples, 1);
is_enl_sample(sample_rows) = true;
enl_top(sample_rows) = roi_manifest.ROITop;
enl_left(sample_rows) = roi_manifest.ROILeft;
assert(sum(is_enl_sample) == 20, ...
    "Table III(a)的ENL样本应为20个。");
end


function group_defs = buildGroupDefinitions( ...
        p_values, p_labels, base_group_defs)
num_p = numel(p_values);
assert(numel(p_labels) == num_p && ...
    numel(unique(p_labels)) == num_p, ...
    "p数值与标签必须一一对应且标签唯一。");
empty_group = struct( ...
    "PIndex", 0, "PLabel", "", "P", 0, "P2", 0, "Q", 0, ...
    "Range_q", 0, "Azimuth_q", 0, ...
    "GroupName", "", "FileKey", "", "GroupType", "", ...
    "RNGGroupIndex", 0);
group_defs = repmat(empty_group, 3 * num_p, 1);

base_names = string({base_group_defs.GroupName});
next_rng_group_idx = numel(base_group_defs) + 1;
ptr = 0;
for p_idx = 1:num_p
    p = p_values(p_idx);
    p2 = snapNearInteger(p ^ 2);
    p_label = p_labels(p_idx);
    p2_label = formatFactor(p2);

    definitions = { ...
        p, p, ...
        "R" + p_label + "A" + p_label, ...
        sprintf("P%02d_Balanced", p_idx), "balanced"; ...
        p2, 1, ...
        "R" + p2_label + "A1", ...
        sprintf("P%02d_RangeOnly", p_idx), "range_only"; ...
        1, p2, ...
        "R1A" + p2_label, ...
        sprintf("P%02d_AzimuthOnly", p_idx), "azimuth_only" ...
    };

    for local_idx = 1:size(definitions, 1)
        group_name = string(definitions{local_idx, 3});
        base_idx = find(base_names == group_name, 1);
        if isempty(base_idx)
            rng_group_idx = next_rng_group_idx;
            next_rng_group_idx = next_rng_group_idx + 1;
        else
            rng_group_idx = base_idx;
        end

        ptr = ptr + 1;
        group_defs(ptr) = makeGroup( ...
            p_idx, p_label, p, p2, ...
            definitions{local_idx, 1}, ...
            definitions{local_idx, 2}, ...
            group_name, ...
            definitions{local_idx, 4}, ...
            definitions{local_idx, 5}, ...
            rng_group_idx);
    end
end

assert(numel(unique([group_defs.RNGGroupIndex])) == numel(group_defs), ...
    "RT小数组的RNG组编号必须唯一。");
assert(all(abs( ...
    [group_defs.Range_q] .* [group_defs.Azimuth_q] - ...
    [group_defs.Q]) < 1e-12), ...
    "RT小数组存在倍率乘积与预算不一致。");
for p_idx = 1:num_p
    current_types = string({ ...
        group_defs([group_defs.PIndex] == p_idx).GroupType});
    assert(isequal(sort(current_types), ...
        sort(["balanced", "range_only", "azimuth_only"])), ...
        "每个p必须恰好包含平衡、距离单向和方位单向三组。");
end

reused_base_names = intersect( ...
    string({group_defs.GroupName}), base_names, "stable");
for base_name = reused_base_names(:).'
    fractional_idx = find( ...
        string({group_defs.GroupName}) == base_name, 1);
    base_idx = find(base_names == base_name, 1);
    assert(~isempty(fractional_idx) && ~isempty(base_idx) && ...
        group_defs(fractional_idx).RNGGroupIndex == base_idx, ...
        "%s未复用Table III(a)的RNG组编号。", base_name);
end
end


function group = makeGroup( ...
        p_idx, p_label, p, p2, range_q, azimuth_q, ...
        group_name, file_key, group_type, rng_group_idx)
group = struct( ...
    "PIndex", p_idx, ...
    "PLabel", string(p_label), ...
    "P", p, ...
    "P2", p2, ...
    "Q", p2, ...
    "Range_q", range_q, ...
    "Azimuth_q", azimuth_q, ...
    "GroupName", string(group_name), ...
    "FileKey", string(file_key), ...
    "GroupType", string(group_type), ...
    "RNGGroupIndex", rng_group_idx);
end


function value = snapNearInteger(value)
if abs(value - round(value)) < 1e-12
    value = round(value);
end
end


function label = formatFactor(value)
value = snapNearInteger(value);
if value == round(value)
    label = string(sprintf("%d", round(value)));
else
    label = string(sprintf("%.15g", value));
end
end


function signature = buildSignature( ...
        cfg, p_values, p_labels, group_defs, ...
        sample_manifest, roi_manifest)
signature = struct( ...
    "experiment", "V4_RTFractionalPAllocationEvaluation", ...
    "seed", cfg.seed, ...
    "As", cfg.As, ...
    "p_values", p_values, ...
    "p_labels", p_labels, ...
    "group_defs", struct2table(group_defs), ...
    "sample_manifest", sample_manifest, ...
    "roi_manifest", roi_manifest, ...
    "entropy_num_bins", cfg.entropy_num_bins, ...
    "enl_window_size", cfg.enl_window_size, ...
    "enl_stride", cfg.enl_stride);
end


function state = evaluateGroup( ...
        group, signature, checkpoint_path, ...
        sample_cache, is_enl_sample, enl_top, enl_left, ...
        S60, cfg)
total_samples = numel(sample_cache);
group_signature = signature;
group_signature.current_group = group;

state = struct( ...
    "signature", group_signature, ...
    "completed_samples", 0, ...
    "rng_state", [], ...
    "PSNR", nan(total_samples, 1), ...
    "SSIM", nan(total_samples, 1), ...
    "Entropy", nan(total_samples, 1), ...
    "ENL", nan(total_samples, 1));

if isfile(checkpoint_path)
    loaded = load(checkpoint_path, "state");
    assert(isfield(loaded, "state") && ...
        isequaln(loaded.state.signature, group_signature), ...
        "检查点签名不一致：%s", checkpoint_path);
    state = loaded.state;
    assert(state.completed_samples >= 0 && ...
        state.completed_samples <= total_samples, ...
        "检查点完成样本数无效：%s", checkpoint_path);
    fprintf("  恢复检查点：%d/%d。\n", ...
        state.completed_samples, total_samples);
else
    rng(cfg.seed + group.RNGGroupIndex);
    state.rng_state = rng;
end

for sample_idx = state.completed_samples + 1:total_samples
    rng(state.rng_state);
    img_gt = sample_cache(sample_idx).img_gt;
    img_out = V4Core.buildSplitRTImage( ...
        sample_cache(sample_idx).signal60_input, S60, ...
        group.Range_q, group.Azimuth_q, cfg.As);
    state.rng_state = rng;

    assert(isequal(size(img_out), size(img_gt)) && ...
        all(isfinite(img_out), "all"), ...
        "%s样本%d的成像尺寸或数值无效。", ...
        group.GroupName, sample_idx);
    state.PSNR(sample_idx) = psnr(img_out, img_gt);
    state.SSIM(sample_idx) = ssim(img_out, img_gt);
    state.Entropy(sample_idx) = ...
        V4Core.imageEntropy(img_out, cfg.entropy_num_bins);
    if is_enl_sample(sample_idx)
        state.ENL(sample_idx) = V4Core.enl( ...
            img_out, enl_top(sample_idx), enl_left(sample_idx), ...
            cfg.enl_window_size);
    end

    state.completed_samples = sample_idx;
    saveCheckpoint(checkpoint_path, state);
    fprintf("  样本 %02d/%02d：PSNR=%.4f dB，SSIM=%.6f\n", ...
        sample_idx, total_samples, ...
        state.PSNR(sample_idx), state.SSIM(sample_idx));
end

assert(all(isfinite(state.PSNR)) && ...
    all(isfinite(state.SSIM)) && ...
    all(isfinite(state.Entropy)) && ...
    all(isfinite(state.ENL(is_enl_sample))) && ...
    all(isnan(state.ENL(~is_enl_sample))), ...
    "%s的checkpoint指标不完整。", group.GroupName);
end


function saveCheckpoint(checkpoint_path, state)
temporary_path = checkpoint_path + ".tmp";
save(temporary_path, "state");
[ok, message] = movefile(temporary_path, checkpoint_path, "f");
assert(ok, "无法更新checkpoint：%s", message);
end


function summary_table = buildSummaryTable( ...
        group_defs, As, ...
        psnr_all, ssim_all, entropy_all, enl_all)
num_groups = numel(group_defs);
PIndex = [group_defs.PIndex].';
PLabel = string({group_defs.PLabel}).';
P = [group_defs.P].';
P2 = [group_defs.P2].';
Q = [group_defs.Q].';
GroupName = string({group_defs.GroupName}).';
Range_q = [group_defs.Range_q].';
Azimuth_q = [group_defs.Azimuth_q].';
GroupType = string({group_defs.GroupType}).';
RNGGroupIndex = [group_defs.RNGGroupIndex].';
SampleCount = repmat(size(psnr_all, 2), num_groups, 1);
ENLSampleCount = sum(~isnan(enl_all), 2);
AsColumn = repmat(As, num_groups, 1);

summary_table = table( ...
    PIndex, PLabel, P, P2, Q, ...
    GroupName, Range_q, Azimuth_q, GroupType, RNGGroupIndex, ...
    SampleCount, ENLSampleCount, AsColumn, ...
    mean(psnr_all, 2), std(psnr_all, 0, 2), ...
    mean(ssim_all, 2), std(ssim_all, 0, 2), ...
    mean(entropy_all, 2), std(entropy_all, 0, 2), ...
    mean(enl_all, 2, "omitnan"), std(enl_all, 0, 2, "omitnan"), ...
    'VariableNames', { ...
    'PIndex', 'PLabel', 'P', 'P2', 'Q', ...
    'GroupName', 'Range_q', 'Azimuth_q', ...
    'GroupType', 'RNGGroupIndex', ...
    'SampleCount', 'ENLSampleCount', 'As', ...
    'PSNR_Mean', 'PSNR_Std', 'SSIM_Mean', 'SSIM_Std', ...
    'Entropy_Mean', 'Entropy_Std', 'ENL_Mean', 'ENL_Std'});
end


